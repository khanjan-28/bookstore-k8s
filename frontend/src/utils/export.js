import * as XLSX from "xlsx";
import { saveAs } from "file-saver";
import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";

// Export Excel
export const exportToExcel = (books) => {

  const data = books.map((book) => ({
    ID: book.id,
    Title: book.title,
    Author: book.author,
    Category: book.category,
    Price: book.price,
    Description: book.description
  }));

  const worksheet = XLSX.utils.json_to_sheet(data);

  const workbook = XLSX.utils.book_new();

  XLSX.utils.book_append_sheet(
    workbook,
    worksheet,
    "Books"
  );

  const excelBuffer = XLSX.write(workbook, {
    bookType: "xlsx",
    type: "array"
  });

  const file = new Blob(
    [excelBuffer],
    {
      type:
        "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"
    }
  );

  saveAs(file, "Books.xlsx");

};

// Export PDF
export const exportToPDF = (books) => {

  const doc = new jsPDF();

  // Title
  doc.setFontSize(20);
  doc.setTextColor(40, 40, 40);
  doc.text("Online Book Store Report", 14, 20);

  // Date
  doc.setFontSize(11);
  doc.setTextColor(100);

  doc.text(
    `Generated: ${new Date().toLocaleString()}`,
    14,
    30
  );

  // Total Books
  doc.text(
    `Total Books: ${books.length}`,
    14,
    37
  );

  // Table
  autoTable(doc, {

    startY: 45,

    head: [[
      "ID",
      "Title",
      "Author",
      "Category",
      "Price"
    ]],

    body: books.map((book) => ([
      book.id,
      book.title,
      book.author,
      book.category,
      `₹ ${book.price}`
    ])),

    headStyles: {
      fillColor: [37, 99, 235],
      textColor: 255,
      fontStyle: "bold"
    },

    alternateRowStyles: {
      fillColor: [245, 245, 245]
    },

    styles: {
      fontSize: 10,
      cellPadding: 3
    }

  });

  // Footer
  const pageHeight = doc.internal.pageSize.height;

  doc.setFontSize(10);
  doc.setTextColor(120);

  doc.text(
    "Generated by Online Book Store Admin Dashboard",
    14,
    pageHeight - 10
  );

  doc.save("Online-Book-Store-Report.pdf");

};
